"""Write a short version's `keep_only` spans (cut-notes.yaml) from word ranges of a take's transcript.

    uv run python scripts/short_spans.py --src projects/<p>/transcript.json --spans <spans>.yaml \
        --out projects/<short>/cut-notes.yaml

`<spans>.yaml`: `take`, `start_s`, `end_s`, `keep` (as in CutNotes) and `spans: [{from: <word i>, to:
    <word i>,
why: ..., end_s: optional override}]`. Each span starts `pad_before` before its first word and ends
    `pad_after`
after its last, but never reaches into a neighbouring word (v1 of the TikTok cut: padding pulled in "I've",
"that", "so" and "Like," from the next sentence).
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

import yaml


def spans(
    words: list[dict[str, Any]], rows: list[dict[str, Any]], before: float, after: float
) -> list[dict[str, Any]]:
    by_i = {w["i"]: k for k, w in enumerate(words)}
    out = []
    for r in rows:
        a, b = by_i[r["from"]], by_i[r["to"]]
        prev_end = words[a - 1]["end_s"] if a > 0 else 0.0
        next_start = words[b + 1]["start_s"] if b + 1 < len(words) else words[b]["end_s"] + after
        s = max(words[a]["start_s"] - before, (prev_end + words[a]["start_s"]) / 2)
        e = min(words[b]["end_s"] + after, (words[b]["end_s"] + next_start) / 2)
        e = r.get("end_s", e)
        out.append({"start_s": round(s, 3), "end_s": round(e, 3), "reason": r["why"]})
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True)
    ap.add_argument("--spans", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--pad-before", type=float, default=0.12)
    ap.add_argument("--pad-after", type=float, default=0.2)
    a = ap.parse_args()
    words = json.loads(Path(a.src).read_text())["words"]
    spec = yaml.safe_load(Path(a.spans).read_text())
    notes = {k: spec[k] for k in ("take", "start_s", "end_s", "keep", "open_with", "close_with") if k in spec}
    notes["keep_only"] = spans(words, spec["spans"], a.pad_before, a.pad_after)
    head = f"# generated by scripts/short_spans.py from {a.spans}; edit that file, not this one\n"
    Path(a.out).write_text(head + yaml.safe_dump(notes, sort_keys=False))
    print(a.out, round(sum(s["end_s"] - s["start_s"] for s in notes["keep_only"]), 1), "s before pauses")


if __name__ == "__main__":
    main()
